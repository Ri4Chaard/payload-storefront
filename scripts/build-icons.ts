/**
 * Generates src/lib/icon-registry.ts from the SVG files in src/assets/icons.
 *
 * The registry is generated rather than hand-maintained for the same reason tokens.css is: the
 * assets are the source of truth, and a hand-copied path is a transcription error waiting to
 * happen. Dropping a new export into src/assets/icons and re-running this is the whole workflow.
 *
 * Only the INNER markup is stored. The `Icon` component owns the <svg> wrapper, so it — not the
 * export — decides sizing, accessibility, and colour.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const SOURCE = resolve(root, 'src/assets/icons')
const OUTPUT = resolve(root, 'src/lib/icon-registry.ts')

interface Entry {
  name: string
  viewBox: string
  body: string
}

const entries: Entry[] = readdirSync(SOURCE)
  .filter((file) => file.endsWith('.svg'))
  .sort()
  .map((file) => {
    const raw = readFileSync(join(SOURCE, file), 'utf8')
    const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1]
    if (!viewBox) throw new Error(`${file} has no viewBox — it cannot be scaled.`)

    const body = raw
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>[\s\S]*$/, '')
      .replace(/\s+/g, ' ')
      .trim()

    // The whole point of the currentColor normalisation is that nothing here names a colour.
    const literal = body.match(/(?:fill|stroke)="(?!none|currentColor)([^"]+)"/)
    if (literal) {
      throw new Error(
        `${file} paints with "${literal[1]}" instead of currentColor. ` +
          `Re-run the normalisation before regenerating the registry.`,
      )
    }

    return { name: file.replace(/\.svg$/, ''), viewBox, body }
  })

const lines = entries.map(
  (entry) =>
    `  '${entry.name}': { viewBox: '${entry.viewBox}', body: '${entry.body.replace(/'/g, "\\'")}' },`,
)

writeFileSync(
  OUTPUT,
  `/**
 * GENERATED by scripts/build-icons.ts from src/assets/icons — do not edit.
 *
 * Run \`pnpm build:icons\` after adding or replacing an SVG.
 */

export interface IconEntry {
  viewBox: string
  body: string
}

export const iconRegistry = {
${lines.join('\n')}
} as const satisfies Record<string, IconEntry>

export type IconName = keyof typeof iconRegistry

export const iconNames = Object.keys(iconRegistry) as IconName[]
`,
)

console.log(`✓ ${entries.length} icons written to src/lib/icon-registry.ts`)
